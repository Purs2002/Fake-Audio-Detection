# 10. CREATE FEATURE MATRIX
# ============================================================

X = feature_df[
    ["jitter", "shimmer"]
].values


# Actual labels
y = feature_df[
    "label"
].map({
    "genuine": 0,
    "fake": 1
}).values


# ============================================================
# 11. STANDARDIZATION
# ============================================================

