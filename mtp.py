# ============================================================
# 5. JITTER + SHIMMER FUNCTION
# ============================================================

def extract_jitter_shimmer(filepath):

    try:

        # Load audio
        sound = parselmouth.Sound(filepath)

        # Create pitch object
        pitch = sound.to_pitch(
            time_step=0.01,
            pitch_floor=75,
            pitch_ceiling=600
        )

        # Create PointProcess
        point_process = parselmouth.praat.call(
            [sound, pitch],
            "To PointProcess (cc)"
        )

        # -------------------------
        # JITTER
        # -------------------------

        jitter = parselmouth.praat.call(
            point_process,
            "Get jitter (local)",
            0,
            0,
            0.0001,
            0.02,
            1.3
        )

        # -------------------------
        # SHIMMER
        # -------------------------

        shimmer = parselmouth.praat.call(
            [sound, point_process],
            "Get shimmer (local)",
            0,
            0,
            0.0001,
            0.02,
            1.3,
            1.6
        )

        return jitter, shimmer

    except Exception as e:

        return np.nan, np.nan


# ============================================================
# 6. EXTRACT FEATURES
# ============================================================

results = []

print("\nExtracting Jitter and Shimmer...")
print("=" * 60)

for i, row in sample_df.iterrows():

    jitter, shimmer = extract_jitter_shimmer(
        row["filepath"]
    )

    results.append({
        "filename": row["filename"],
        "label": row["label"],
        "filepath": row["filepath"],
        "jitter": jitter,
        "shimmer": shimmer
    })

    if (i + 1) % 50 == 0:

        print(
            f"Processed {i+1}/{len(sample_df)}"
        )


# ============================================================
# 7. CREATE FEATURE DATAFRAME
# ============================================================

feature_df = pd.DataFrame(results)


print("\nFeature dataframe:")
display(feature_df.head())


# ============================================================
# 8. REMOVE INVALID FEATURES
# ============================================================

feature_df = feature_df.dropna(
    subset=["jitter", "shimmer"]
)

feature_df = feature_df[
    np.isfinite(feature_df["jitter"]) &
    np.isfinite(feature_df["shimmer"])
].copy()


print("\nValid samples:")
print(len(feature_df))

